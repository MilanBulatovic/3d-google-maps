/** True when the point sits inside the Montenegro outline. */
export function isInMontenegro(latitude: number, longitude: number): boolean {
  let inside = false;

  for (let index = 0, previous = MONTENEGRO_OUTLINE.length - 1; index < MONTENEGRO_OUTLINE.length; previous = index++) {
    const [currentLongitude, currentLatitude] = MONTENEGRO_OUTLINE[index];
    const [previousLongitude, previousLatitude] = MONTENEGRO_OUTLINE[previous];
    const crossesLatitude = currentLatitude > latitude !== previousLatitude > latitude;
    const longitudeAtLatitude =
      ((previousLongitude - currentLongitude) * (latitude - currentLatitude)) /
        (previousLatitude - currentLatitude) +
      currentLongitude;

    if (crossesLatitude && longitude < longitudeAtLatitude) {
      inside = !inside;
    }
  }

  return inside;
}
